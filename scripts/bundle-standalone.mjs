#!/usr/bin/env node
/*
 * Inlines the whole app into one self-contained HTML file:
 *   build/standalone.html
 *
 * The app is written as plain ES modules with no dependencies, so instead of
 * pulling in a bundler we wrap each module in a tiny CommonJS-style registry.
 * The result opens straight from disk (file://) and is what the desktop build
 * loads, since Chromium refuses to fetch ES modules over file://.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'src');
const outDir = path.join(root, 'build');
const ENTRY = 'main.js';

/* ------------------------------- collect ------------------------------- */

function walk(dir, base = '') {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...walk(path.join(dir, entry.name), rel));
    else if (entry.name.endsWith('.js')) out.push(rel);
  }
  return out;
}

/* ------------------------------ transform ------------------------------ */

const IMPORT_RE = /^[ \t]*import\s+([\s\S]*?)\s+from\s+['"]([^'"]+)['"];?[ \t]*$/gm;
const SIDE_IMPORT_RE = /^[ \t]*import\s+['"]([^'"]+)['"];?[ \t]*$/gm;

function resolveId(fromId, spec) {
  if (!spec.startsWith('.')) throw new Error(`Bare import "${spec}" in ${fromId} — the app must stay dependency-free.`);
  const joined = path.posix.join(path.posix.dirname(fromId), spec);
  return path.posix.normalize(joined).replace(/^\.\//, '');
}

function transform(id, code) {
  const exported = new Set();
  let out = code;

  out = out.replace(SIDE_IMPORT_RE, (_m, spec) => `__require(${JSON.stringify(resolveId(id, spec))});`);

  out = out.replace(IMPORT_RE, (_m, clause, spec) => {
    const target = JSON.stringify(resolveId(id, spec));
    const c = clause.trim();
    if (c.startsWith('*')) {
      const ns = c.replace(/^\*\s*as\s*/, '').trim();
      return `const ${ns} = __require(${target});`;
    }
    if (c.startsWith('{')) {
      const inner = c.slice(c.indexOf('{') + 1, c.lastIndexOf('}'))
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean)
        .map((s) => {
          const parts = s.split(/\s+as\s+/);
          return parts.length === 2 ? `${parts[0].trim()}: ${parts[1].trim()}` : parts[0].trim();
        })
        .join(', ');
      return `const { ${inner} } = __require(${target});`;
    }
    throw new Error(`Unsupported import form in ${id}: ${c}`);
  });

  // export function / class / const / let
  out = out.replace(/^[ \t]*export\s+(async\s+function|function|class|const|let)\s+([A-Za-z_$][\w$]*)/gm,
    (_m, kind, name) => {
      exported.add(name);
      return `${kind} ${name}`;
    });

  if (/^\s*export\s/m.test(out)) {
    const leftover = out.match(/^\s*export\s.*/m);
    throw new Error(`Unsupported export form in ${id}: ${leftover && leftover[0].trim()}`);
  }

  const tail = exported.size
    ? `\nObject.assign(exports, { ${[...exported].join(', ')} });\n`
    : '';
  return `/* ---- ${id} ---- */\n${out}${tail}`;
}

/* -------------------------------- build -------------------------------- */

const files = walk(srcDir).filter((f) => f !== ENTRY);
files.push(ENTRY);   // entry last, purely for readability

const modules = files.map((id) => {
  const code = fs.readFileSync(path.join(srcDir, id), 'utf8');
  return `${JSON.stringify(id)}: function (exports, __require) {\n${transform(id, code)}\n}`;
});

const runtime = `
(function () {
  var __defs = {
${modules.join(',\n')}
  };
  var __cache = {};
  function __require(id) {
    if (__cache[id]) return __cache[id].exports;
    var mod = { exports: {} };
    __cache[id] = mod;
    var def = __defs[id];
    if (!def) throw new Error('Module not bundled: ' + id);
    def(mod.exports, __require);
    return mod.exports;
  }
  __require(${JSON.stringify(ENTRY)});
})();
`;

const css = fs.readFileSync(path.join(srcDir, 'styles.css'), 'utf8');
let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');

html = html.replace(/<link rel="stylesheet" href="src\/styles\.css">/,
  `<style>\n${css}\n</style>`);
html = html.replace(/<script type="module" src="src\/main\.js"><\/script>/,
  `<script>\n${runtime}\n</script>`);
html = html.replace('<title>', '<!-- Single-file build — generated by scripts/bundle-standalone.mjs -->\n<title>');

// Icons become data URIs and the manifest link goes, so the one file has no
// siblings to find. (A hosted copy still gets the real files from index.html.)
html = html.replace(/href="(assets\/[\w.-]+\.png)"/g, (match, rel) => {
  const file = path.join(root, rel);
  if (!fs.existsSync(file)) {
    console.warn(`warning: ${rel} is missing — run scripts/make-icon.mjs`);
    return match;
  }
  return `href="data:image/png;base64,${fs.readFileSync(file).toString('base64')}"`;
});
html = html.replace(/[ \t]*<link rel="manifest"[^>]*>\n/, '');

if (html.includes('src/styles.css') || html.includes('src/main.js')) {
  throw new Error('index.html did not match the expected asset tags — bundler needs updating.');
}
if (/(href|src)="(?!data:|#)/.test(html)) {
  const stray = html.match(/(href|src)="(?!data:|#)[^"]*"/);
  throw new Error(`standalone build still points at an external file: ${stray && stray[0]}`);
}

fs.mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, 'standalone.html');
fs.writeFileSync(outFile, html);

const kb = (fs.statSync(outFile).size / 1024).toFixed(0);
console.log(`built ${path.relative(root, outFile)} — ${kb} KB, ${files.length} modules inlined`);
